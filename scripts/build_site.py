#!/usr/bin/env python3
"""Build the GitHub Pages site in docs/ from the JSON registers in docs/data/.

Every table on the site is rendered from a JSON file, so a number or status appears in one place only.
Run: python scripts/build_site.py   (idempotent; writes docs/*.html)
"""
from __future__ import annotations

import html
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
DATA = DOCS / "data"
UPDATED = "2026-10-11"


def load(name):
    return json.loads((DATA / name).read_text(encoding="utf-8"))


def e(x) -> str:
    return html.escape("" if x is None else str(x))


def nz(x) -> str:
    """Render a missing value explicitly, never as blank."""
    return "<em>not measured</em>" if x is None else e(x)


def tag(status: str) -> str:
    s = status.upper()
    if s.startswith(("VERIFIED", "CONFIRMED")):
        cls = "green"
    elif s.startswith(("CONTRADICTED", "BLOCK", "BROKEN", "NOT ACCESSED", "NOT FETCHED", "NEEDS", "DENIED")) or "NOT VERIFIED" in s or "NOT MEASURED" in s:
        cls = "red"
    elif s.startswith(("PARTIAL", "OPEN", "UNVERIFIED", "UNATTRIBUTED", "PROJECTION", "THIRD-PARTY", "OWNER", "NOTED", "ASSUMPTION", "CITED", "UNKNOWN", "POLICY", "CORRECTED", "NEEDS")):
        cls = "amber"
    else:
        cls = "grey"
    return f'<span class="tag {cls}">{e(status)}</span>'


OFFICIAL_LEADERBOARD_URL = "https://www.drivendata.org/competitions/306/competition-doe-gems/leaderboard/"
NAV = [("index.html", "Summary"), ("submission-guide.html", "How to submit"),
       ("analysis.html", "H33 attribution"), ("hypotheses.html", "Hypotheses"),
       (OFFICIAL_LEADERBOARD_URL, "Official leaderboard ↗"), ("run-card.html", "Run card"),
       ("irregularities.html", "Irregularities"), ("sources.html", "Sources"),
       ("research/metric-derivation.md", "Metric derivation")]


def _nav_href(href: str, prefix: str) -> str:
    return href if href.startswith(("https://", "http://")) else prefix + href


def page(filename: str, title: str, body: str, active: str) -> None:
    prefix = "../" if "/" in filename else ""
    nav = "".join(
        f'<a href="{_nav_href(href, prefix)}" class="{"active" if href == active else ""}">{e(label)}</a>'
        for href, label in NAV)
    doc = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{e(title)} · GEMS Prize workbench</title>
<link rel="stylesheet" href="{prefix}assets/site.css">
</head>
<body>
<header class="site">
  <div class="brand">GEMS Prize (DrivenData #306) · workbench</div>
  <nav>{nav}</nav>
</header>
<main>
{body}
</main>
<footer>Generated by scripts/build_site.py from docs/data/*.json · last updated {UPDATED} (UTC) · not affiliated with DrivenData or DOE.</footer>
</body>
</html>
"""
    (DOCS / filename).parent.mkdir(parents=True, exist_ok=True)
    (DOCS / filename).write_text(doc, encoding="utf-8")


